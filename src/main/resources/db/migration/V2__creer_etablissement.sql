-- V2 : les établissements de la plateforme (SaaS). Une clinique pour l'instant.
create table etablissement (
    id                 integer generated by default as identity,
    creation_date      timestamp(6) with time zone not null,
    last_modified_date timestamp(6) with time zone not null,
    nom                varchar(255) not null,
    type               varchar(255) not null
        check (type in ('CLINIQUE','CABINET','PHARMACIE','LABORATOIRE')),
    adresse            varchar(255),
    ville              varchar(255),
    telephone          varchar(255),
    email              varchar(255),
    actif              boolean not null default true,
    primary key (id)
);
