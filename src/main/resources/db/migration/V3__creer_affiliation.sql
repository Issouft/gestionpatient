-- V3 : les affiliations (tel compte a tel rôle dans tel établissement).
create table affiliation (
    id                 integer generated by default as identity,
    creation_date      timestamp(6) with time zone not null,
    last_modified_date timestamp(6) with time zone not null,
    utilisateur_id     integer not null,
    etablissement_id   integer not null,
    role               varchar(255) not null
        check (role in ('MEDECIN','SECRETAIRE','PATIENT','PHARMACIEN','ADMINISTRATEUR')),
    statut             varchar(255) not null default 'ACTIVE'
        check (statut in ('ACTIVE','SUSPENDUE')),
    primary key (id),
    constraint uk_affiliation_utilisateur_etablissement_role unique (utilisateur_id, etablissement_id, role),
    constraint fk_affiliation_utilisateur foreign key (utilisateur_id) references utilisateur,
    constraint fk_affiliation_etablissement foreign key (etablissement_id) references etablissement
);

-- Les bases qui existaient avant le SaaS n'avaient qu'un seul établissement, sans le dire.
-- S'il y a déjà des comptes, on crée cet établissement (« Clinique principale ») et on y rattache
-- chaque compte avec son rôle actuel. Sur une base neuve, il n'y a aucun compte : rien n'est créé.
insert into etablissement (creation_date, last_modified_date, nom, type, actif)
select now(), now(), 'Clinique principale', 'CLINIQUE', true
where exists (select 1 from utilisateur);

insert into affiliation (creation_date, last_modified_date, utilisateur_id, etablissement_id, role, statut)
select now(), now(), u.id, e.id, u.role, 'ACTIVE'
from utilisateur u
cross join (select min(id) as id from etablissement) e
where e.id is not null;
