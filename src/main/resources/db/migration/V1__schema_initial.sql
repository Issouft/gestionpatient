-- Un seul dossier par patient (patient_id unique).
create table dossier_patient (
    id                 integer generated by default as identity,
    creation_date      timestamp(6) with time zone not null,
    last_modified_date timestamp(6) with time zone not null,
    patient_id         integer not null unique,
    secretaire_id      integer,
    antecedents        varchar(255),
    primary key (id)
);

-- Une seule consultation par rendez-vous (rendez_vous_id unique).
create table consultation (
    id                 integer generated by default as identity,
    creation_date      timestamp(6) with time zone not null,
    last_modified_date timestamp(6) with time zone not null,
    date_consultation  timestamp(6) with time zone,
    observations       varchar(255),
    diagnostic         varchar(255),
    dossier_patient_id integer not null,
    medecin_id         integer not null,
    rendez_vous_id     integer not null unique,
    primary key (id)
);

-- Une seule ordonnance par consultation (consultation_id unique).
create table ordonnance (
    id                 integer generated by default as identity,
    creation_date      timestamp(6) with time zone not null,
    last_modified_date timestamp(6) with time zone not null,
    date_emission      timestamp(6) with time zone,
    consultation_id    integer not null unique,
    primary key (id)
);

create table medicament (
    id                 integer generated by default as identity,
    creation_date      timestamp(6) with time zone not null,
    last_modified_date timestamp(6) with time zone not null,
    nom                varchar(255),
    dosage             varchar(255),
    stock              integer not null,
    seuil_alerte       integer,
    pharmacien_id      integer,
    primary key (id)
);

create table ligne_ordonnance (
    id                 integer generated by default as identity,
    creation_date      timestamp(6) with time zone not null,
    last_modified_date timestamp(6) with time zone not null,
    ordonnance_id      integer not null,
    medicament_id      integer not null,
    quantite           integer not null,
    posologie          varchar(255),
    duree_jours        integer,
    primary key (id)
);

create table demande_disponibilite (
    id                 integer generated by default as identity,
    creation_date      timestamp(6) with time zone not null,
    last_modified_date timestamp(6) with time zone not null,
    date_demande       timestamp(6) with time zone,
    quantite           integer default 1 not null,
    statut             varchar(255) not null check (statut in ('EN_ATTENTE','VALIDEE','REFUSEE')),
    reponse            varchar(255),
    date_retrait       timestamp(6) with time zone,
    patient_id         integer not null,
    medicament_id      integer not null,
    pharmacien_id      integer,
    primary key (id)
);

create table rapport (
    id                 integer generated by default as identity,
    creation_date      timestamp(6) with time zone not null,
    last_modified_date timestamp(6) with time zone not null,
    type_rapport       varchar(255)
        check (type_rapport in ('ACTIVITE_MEDICALE','RENDEZ_VOUS','STOCK_MEDICAMENTS')),
    periode_debut      timestamp(6) with time zone,
    periode_fin        timestamp(6) with time zone,
    date_generation    timestamp(6) with time zone,
    resume_rapport     varchar(255),
    administrateur_id  integer not null,
    primary key (id)
);

