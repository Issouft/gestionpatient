-- ============================================================
-- Partie 1 : comptes (utilisateur)
-- ============================================================

-- Un compte. Chaque rôle a sa table, liée par le même id (héritage JOINED).
create table utilisateur (
    id                      integer generated by default as identity,
    creation_date           timestamp(6) with time zone not null,
    last_modified_date      timestamp(6) with time zone not null,
    nom                     varchar(255),
    prenom                  varchar(255),
    email                   varchar(255) not null unique,
    mot_de_passe_hash       varchar(255) not null,
    mot_de_passe_modifie_le timestamp(6) with time zone,
    actif                   boolean not null,
    role                    varchar(255) not null
        check (role in ('MEDECIN','SECRETAIRE','PATIENT','PHARMACIEN','ADMINISTRATEUR')),
    primary key (id)
);

create table administrateur (
    id integer not null,
    primary key (id)
);

create table medecin (
    id           integer not null,
    numero_ordre varchar(255) unique,
    specialite   varchar(255),
    primary key (id)
);

create table secretaire (
    id integer not null,
    primary key (id)
);

create table pharmacien (
    id integer not null,
    primary key (id)
);

create table patient (
    id             integer not null,
    date_naissance date,
    sexe           varchar(255) check (sexe in ('MASCULIN','FEMININ')),
    telephone      varchar(255),
    adresse        varchar(255),
    primary key (id)
);

-- Liens envoyés par email (activation, mot de passe oublié). Seule l'empreinte du jeton est gardée.
create table jeton_activation (
    id                 integer generated by default as identity,
    creation_date      timestamp(6) with time zone not null,
    last_modified_date timestamp(6) with time zone not null,
    utilisateur_id     integer not null,
    jeton_hash         varchar(255) not null unique,
    expiration         timestamp(6) with time zone not null,
    utilise            boolean not null,
    primary key (id)
);

