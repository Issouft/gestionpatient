-- ============================================================
-- Partie 2 : rendez-vous
-- ============================================================

create table planning (
    id                 integer generated by default as identity,
    creation_date      timestamp(6) with time zone not null,
    last_modified_date timestamp(6) with time zone not null,
    medecin_id         integer not null unique,
    primary key (id)
);

create table creneau (
    id                 integer generated by default as identity,
    creation_date      timestamp(6) with time zone not null,
    last_modified_date timestamp(6) with time zone not null,
    planning_id        integer not null,
    date               date,
    heure_debut        time(0),
    heure_fin          time(0),
    disponible         boolean not null,
    primary key (id)
);

create table rendez_vous (
    id                 integer generated by default as identity,
    creation_date      timestamp(6) with time zone not null,
    last_modified_date timestamp(6) with time zone not null,
    date_heure         timestamp(6),
    motif              varchar(255),
    statut_rendez_vous varchar(255) not null
        check (statut_rendez_vous in ('EN_ATTENTE','CONFIRME','REJETE','REPORTE','ANNULE','TERMINE')),
    patient_id         integer not null,
    medecin_id         integer not null,
    secretaire_id      integer,
    creneau_id         integer unique,
    primary key (id)
);

create table notification (
    id                 integer generated by default as identity,
    creation_date      timestamp(6) with time zone not null,
    last_modified_date timestamp(6) with time zone not null,
    destinataire_id    integer not null,
    message            varchar(255),
    type_notification  varchar(255)
        check (type_notification in ('RAPPEL_RDV','CONFIRMATION_RDV','ANNULATION_RDV','REPONSE_DEMANDE','ALERTE_STOCK')),
    date_envoi         timestamp(6),
    lue                boolean not null,
    primary key (id)
);

